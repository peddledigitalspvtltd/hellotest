import { fulfillAutomationFixtureRequest } from './helpers/automationFixtureTransport.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import {writeFile,rm,mkdir} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../../../../testengine/backend/package.json',import.meta.url));
const {chromium}=require('playwright');
const expect=require('playwright/test').expect.configure({timeout:15000});
const root=new URL('../../../platform/frontend/',import.meta.url);
const fixture=`import React from 'react';import {createRoot} from 'react-dom/client';import {ApiAutomationSourceIntake} from '/services/automation/frontend/components/ApiAutomationSourceIntake';import '/src/product-experience.css';
window.intakeReceipts=[];
createRoot(document.getElementById('root')).render(<main style={{maxWidth:880,margin:'24px auto',padding:'0 12px',minWidth:0}}><h1>Prepare API request steps</h1><ApiAutomationSourceIntake hasSteps onApply={(result,mode)=>{if(window.rejectNextIntake)return 'Parameter defaults conflict for orderId.';window.intakeReceipts.push({result,mode});}}/></main>);`;

test('API source intake previews ordered requests, protects credentials, applies Add/Replace explicitly and fits mobile', {timeout:120000}, async()=>{
 const name='api-source-intake-'+randomUUID();let browser;
 try{
  await writeFile(new URL(name+'.tsx',root),fixture);
  await writeFile(new URL(name+'.html',root),`<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><div id="root"></div><script type="module" src="/${name}.tsx"></script></body></html>`);
  browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_EXECUTABLE||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  const page=await browser.newPage({viewport:{width:1440,height:1050}});page.setDefaultTimeout(15000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.route('**/api/**',async route=>{if (await fulfillAutomationFixtureRequest(page, route)) return;errors.push('Unexpected API request '+route.request().url());return route.abort();});
  await page.goto(`${process.env.VITE_TEST_URL||'http://127.0.0.1:5197'}/${name}.html`,{waitUntil:'domcontentloaded',timeout:60000});
  const source=page.getByRole('textbox',{name:'API source',exact:true});
  const curl=`curl 'https://api.example.test/orders' -H 'Authorization: Bearer private-fixture-token'\ncurl -X POST 'https://api.example.test/orders' -H 'Content-Type: application/json' --data-raw '{"name":"Example"}'\ncurl -X DELETE 'https://api.example.test/orders/123'`;
  await source.fill(curl);await page.getByRole('button',{name:'Review requests',exact:true}).click();
  await expect(page.locator('.api-source-intake-review')).toBeVisible();
  assert.deepEqual(await page.locator('.api-source-method').allTextContents(),['GET','POST','DELETE']);
  assert.deepEqual(await page.locator('.api-source-url').allTextContents(),['https://api.example.test/orders','https://api.example.test/orders','https://api.example.test/orders/123']);
  await expect(page.locator('.api-source-intake-review')).not.toContainText('private-fixture-token');
  await expect(page.getByRole('combobox',{name:'Apply API requests'})).toHaveValue('append');
  assert.equal(await page.evaluate(()=>window.intakeReceipts.length),0);
  await mkdir('/tmp/qaira-api-source-intake',{recursive:true});
  await page.locator('.api-source-intake').screenshot({path:'/tmp/qaira-api-source-intake/desktop.png'});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.locator('.api-source-intake').evaluate(element=>element.scrollWidth<=element.clientWidth+1),'Source intake fits the mobile viewport.');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'The page has no horizontal overflow.');
  await page.locator('.api-source-intake').screenshot({path:'/tmp/qaira-api-source-intake/mobile.png'});
  await page.evaluate(()=>{window.rejectNextIntake=true;});
  await page.getByRole('button',{name:'Add 3 API request steps',exact:true}).click();
  await expect(page.locator('.api-source-intake-review')).toBeVisible();
  await expect(page.getByRole('alert')).toHaveText('Parameter defaults conflict for orderId.');
  assert.equal(await page.evaluate(()=>window.intakeReceipts.length),0,'A rejected draft application preserves its review and input.');
  await page.evaluate(()=>{window.rejectNextIntake=false;});
  await page.getByRole('button',{name:'Add 3 API request steps',exact:true}).click();
  const first=await page.evaluate(()=>window.intakeReceipts[0]);
  assert.equal(first.mode,'append');assert.equal(first.result.steps.length,3);
  assert.doesNotMatch(JSON.stringify(first),/private-fixture-token/);
  assert.ok(first.result.steps.every(step=>step.expected_result===''));
  await source.fill(curl);await page.getByRole('button',{name:'Review requests',exact:true}).click();
  await page.getByRole('combobox',{name:'Apply API requests'}).selectOption('replace');
  await page.getByRole('button',{name:'Use 3 API request steps',exact:true}).click();
  assert.equal(await page.evaluate(()=>window.intakeReceipts[1].mode),'replace');
  await source.fill('curl https://api.example.test --form file=@private.txt');
  await page.getByRole('button',{name:'Review requests',exact:true}).click();
  await expect(page.getByRole('alert')).toBeVisible();
  assert.equal(await page.locator('.api-source-intake-review').count(),0);
  assert.equal(await page.evaluate(()=>window.intakeReceipts.length),2);
  await page.getByLabel('API source file',{exact:true}).setInputFiles({name:'requests.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({info:{name:'Captured login'},item:[{name:'Sign in',request:{method:'POST',url:'https://api.example.test/login',body:{mode:'raw',raw:'{"password":"private-file-password"}',options:{raw:{language:'json'}}}},response:[{code:201}]}]}))});
  await expect(source).toContainText('private-file-password');
  await page.getByRole('button',{name:'Review requests',exact:true}).click();
  await expect(page.locator('.api-source-intake-review')).not.toContainText('private-file-password');
  await expect(page.locator('.api-source-intake-review')).toContainText('1 request prepared');
  await page.getByLabel('API source file',{exact:true}).setInputFiles({name:'too-large.json',mimeType:'application/json',buffer:Buffer.alloc(2*1024*1024+1,32)});
  await expect(page.getByRole('alert')).toContainText('2 MB');await expect(source).toHaveValue('');
  assert.equal(await page.locator('.api-source-intake-review').count(),0);
  assert.deepEqual(errors,[]);
 }finally{await browser?.close();await rm(new URL(name+'.tsx',root),{force:true});await rm(new URL(name+'.html',root),{force:true});}
});
