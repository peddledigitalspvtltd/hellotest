test('builder annotations forbid whole-case retry after a confirmed interaction', () => {
  const start = source.indexOf('const annotateBuildFailure=error=>'), end = source.indexOf('const generationEvidence=', start);
  assert.ok(start >= 0 && end > start);
  const annotate = observations => new Function('test_case_id', 'preparedTarget', 'savedSectionIds', 'completionActiveStepId', 'completionActiveManualStepIds', 'browserObservations', `${source.slice(start, end)};return annotateBuildFailure;`)(
    'automation-case', { source_test_case_id: 'manual-case' }, new Set(['one']), 'two', ['manual-two'], observations);
  for (const tool of ['browser_click', 'browser_fill', 'browser_press_key', 'browser_select_option', 'browser_check', 'browser_uncheck', 'browser_hover']) {
    const error = createLlmProviderError({ status: 429, retryAfterMs: 46005 });
    annotate([{ tool, result: { content: [{ type: 'text', text: '{"action_outcome":"completed"}' }] } }])(error);
    assert.equal(error.nonRetryable, true); assert.equal(error.active_step_id, 'two'); assert.deepEqual(error.saved_step_ids, ['one']);
  }
  const notAttempted = createLlmProviderError({ status: 429, retryAfterMs: 46005 });
  annotate([{ tool: 'browser_click', result: { isError: true, content: [{ type: 'text', text: '{"action_outcome":"not_attempted"}' }] } }])(notAttempted);
  assert.notEqual(notAttempted.nonRetryable, true, 'an explicit pre-action rejection alone does not claim that an interaction happened');
});
