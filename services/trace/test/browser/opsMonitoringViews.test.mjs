import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';
import { writeFile, rm } from 'node:fs/promises';
const require = createRequire(new URL('../../../../testengine/backend/package.json', import.meta.url));
const { chromium } = require('playwright');
const root = new URL('../../../platform/frontend/', import.meta.url);

test('Test Ops shows dashboard, logs, alerts, independent failure states and administrator scope', { timeout: 90000 }, async () => {
  const name = `ops-monitoring-${randomUUID()}`;
  let browser;
  const fixture = `
import ReactDOM from 'react-dom/client';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { MemoryRouter } from 'react-router-dom';
import { AuthProvider } from '/src/auth/AuthContext';
import { api, sessionStorage } from '/src/lib/api';
import { OpsMonitoringWorkspace } from '/services/trace/frontend/components/OpsMonitoringWorkspace';
import '/src/styles.css';
const role = new URLSearchParams(location.search).get('role') || 'admin';
const session = { token: 'fixture', user: { id: 'qa', role, email: 'qa@example.test', name: 'QA' } };
sessionStorage.write(session);
api.auth.session = async () => session;
api.featureFlags.snapshot = async () => ({ flags: { 'hellotest.ops.telemetry': true }, dependencies: {} });
api.admin.health = async () => ({ status: 'ready', checked_at: new Date().toISOString(), checks: [{ key: 'db', label: 'Primary database', status: 'ready', summary: 'Database available' }] });
let grafanaAttempts = 0;
api.opsTelemetry.grafanaSession = async () => {
  if (new URLSearchParams(location.search).has('grafana_outage') && grafanaAttempts++ === 0) throw new Error('Grafana connection unavailable');
  return { url: '/__grafana-fixture.html', expires_at: new Date(Date.now()+900000).toISOString() };
};
const consoleAttempts = {};
api.opsTelemetry.consoleSession = async (_project, provider) => {
  if (role !== 'admin') throw new Error('Member must not request an infrastructure console');
  consoleAttempts[provider] = (consoleAttempts[provider] || 0) + 1;
  if (new URLSearchParams(location.search).has(provider + '_outage') && consoleAttempts[provider] === 1) throw new Error('Console connection unavailable');
  return { url: '/__console-' + provider + '.html', expires_at: new Date(Date.now()+900000).toISOString() };
};
api.opsTelemetry.monitoring = async (_project, section) => {
  if (role !== 'admin') throw new Error('Member must not request infrastructure data');
  const base = { section, state: 'available', checked_at: new Date().toISOString() };
  if (section === 'dashboard') return { ...base, metrics: [{ id: 'rate', label: 'API requests / second', value: 12.5, unit: 'req/s' }], services: [{ name: 'hellotest-api', available: true }] };
  if (section === 'logs') return new URLSearchParams(location.search).has('outage') ? { ...base, state: 'unavailable' } : { ...base, logs: [{ timestamp: '1', time: new Date().toISOString(), container: 'hellotest-local-api', message: 'Test execution completed safely' }] };
  return { ...base, alerts: [{ id: '1', name: 'ServiceDown', severity: 'warning', state: 'active', summary: 'Worker is offline', description: 'Other services remain available', starts_at: new Date().toISOString() }] };
};
api.opsTelemetry.platform = async () => ({ state: 'available', enabled: true, checked_at: new Date().toISOString(), components: [{id:'prometheus',purpose:'Metrics',state:'available',memory_limit_mib:256}], policy: {} });
ReactDOM.createRoot(document.getElementById('root')).render(<QueryClientProvider client={new QueryClient({defaultOptions:{queries:{retry:false}}})}><AuthProvider><MemoryRouter><OpsMonitoringWorkspace projectId="project-1"><p>Project execution event fixture</p></OpsMonitoringWorkspace></MemoryRouter></AuthProvider></QueryClientProvider>);
`;
  try {
    await writeFile(new URL(`${name}.tsx`, root), fixture);
    await writeFile(new URL(`${name}.html`, root), `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><div id="root"></div><script type="module" src="/${name}.tsx"></script></body></html>`);
    browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_EXECUTABLE || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    await page.route('**/__grafana-fixture.html', route => route.fulfill({contentType:'text/html', body:'<!doctype html><h1>Grafana dashboard fixture</h1>'}));
    await page.route('**/__console-*.html', route => route.fulfill({contentType:'text/html', body:'<!doctype html><h1>Embedded console ready</h1>'}));
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const url = `${process.env.VITE_TEST_URL || 'http://127.0.0.1:5191'}/${name}.html`;
    await page.goto(url);
    await page.getByText('API requests / second', { exact: true }).waitFor();
    await page.screenshot({ path: '/tmp/hellotest-ops-dashboard.png' });
    assert.equal(await page.getByText('Project execution event fixture').count(), 0);
    await page.getByRole('tab', { name: 'TestGrid telemetry', exact: true }).click();
    await page.getByText('Project execution event fixture').waitFor();
    assert.equal(await page.getByText('API requests / second', { exact: true }).count(), 0);
    await page.getByRole('tab', { name: 'Grafana dashboard', exact: true }).click();
    await page.locator('iframe[title="Grafana runtime dashboard"]').waitFor();
    await page.getByRole('tab', { name: 'Infrastructure logs', exact: true }).click();
    await page.getByText('Test execution completed safely', { exact: true }).waitFor();
    await page.getByRole('searchbox').fill('no-match');
    await page.getByText('No loaded log lines match this filter.').waitFor();
    await page.getByRole('tab', { name: 'Service health', exact: true }).click();
    await page.getByText('Primary database', { exact: true }).waitFor();
    await page.getByText('prometheus', { exact: true }).waitFor();
    await page.screenshot({ path: '/tmp/hellotest-ops-health.png' });
    await page.getByRole('tab', { name: 'Alertmanager', exact: true }).click();
    await page.locator('iframe[title="Alertmanager console"]').waitFor();
    assert.equal(await page.getByRole('link', { name: /^Open / }).count(), 0);
    await page.getByRole('tab', { name: 'Distributed traces', exact: true }).click();
    await page.locator('iframe[title="Jaeger distributed traces"]').waitFor();
    assert.equal(await page.locator('iframe').count(), 1, 'only the active console should stay mounted');
    await page.screenshot({ path: '/tmp/hellotest-ops-traces-tab.png' });
    await page.goto(`${url}?traces_outage=1`);
    await page.getByRole('tab', { name: 'Distributed traces', exact: true }).click();
    await page.getByRole('alert').getByText('Distributed traces unavailable').waitFor();
    await page.getByRole('button', { name: 'Reconnect', exact: true }).click();
    await page.locator('iframe[title="Jaeger distributed traces"]').waitFor();
    await page.goto(`${url}?grafana_outage=1`);
    await page.getByRole('tab', { name: 'Grafana dashboard', exact: true }).click();
    await page.getByRole('alert').getByText('Grafana dashboard unavailable').waitFor();
    await page.getByRole('button', { name: 'Reconnect', exact: true }).click();
    await page.locator('iframe[title="Grafana runtime dashboard"]').waitFor();
    await page.goto(`${url}?outage=1`);
    await page.getByRole('tab', { name: 'Infrastructure logs', exact: true }).click();
    await page.getByText(/Loki is temporarily unavailable/).waitFor();
    await page.getByRole('tab', { name: 'Alertmanager', exact: true }).click();
    await page.locator('iframe[title="Alertmanager console"]').waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'monitoring must not overflow on mobile');
    await page.getByRole('tab', { name: 'Service health', exact: true }).click();
    await page.getByText('prometheus', { exact: true }).waitFor();
    await page.screenshot({ path: '/tmp/hellotest-ops-mobile.png' });
    await page.goto(`${url}?role=member`);
    await page.getByText(/Workspace administrator access is required/).waitFor();
    await page.getByRole('tab', { name: 'Service health', exact: true }).click();
    await page.getByText('prometheus', { exact: true }).waitFor();
    assert.deepEqual(errors, []);
  } finally {
    await browser?.close();
    await Promise.all(['tsx', 'html'].map(extension => rm(new URL(`${name}.${extension}`, root), { force: true })));
  }
});
