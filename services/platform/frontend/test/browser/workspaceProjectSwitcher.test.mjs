  assert.deepEqual(await page.evaluate(()=>window.__scopeFixture.requests),['p1'],'initial render queries only the selected project');
  assert.deepEqual(await page.evaluate(()=>window.__scopeFixture.events),[],'loading does not write defaults');
  await projectTrigger().click();
