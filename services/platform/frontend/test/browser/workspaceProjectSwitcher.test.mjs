  assert.equal((await scope()).apps.p2,'gateway','fetch failure preserves remembered application');
  await page.evaluate(()=>{window.__scopeFixture.fail=false;});
  await page.getByRole('button',{name:'Try again',exact:true}).click();
  await page.getByRole('option',{name:/Payment gateway/}).waitFor();
  await page.getByRole('button',{name:'Outside control'}).click();
  assert.equal(await page.locator('.workspace-scope-menu').count(),0,'outside interaction dismisses menu');

  await chooseProject('Research workspace');
