  assert.deepEqual(errors,[]);
  console.log('PASS: scoped and permission-specific cache/late responses; explicit-only atomic selections; preserved memory on load/error/empty; guarded changes; retry/search; keyboard/outside/Escape; long labels; collapsed/mobile/dark menus.');
