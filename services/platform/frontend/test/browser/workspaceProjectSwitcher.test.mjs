  await page.getByRole('alert').filter({hasText:'Couldn’t switch workspace'}).waitFor();
  assert.equal((await scope()).project,'p3','guard failure cannot change scope');
  await page.keyboard.press('Escape');
  await page.evaluate(()=>{window.__scopeFixture.guardMode='delay';});
  await projectTrigger().click();
