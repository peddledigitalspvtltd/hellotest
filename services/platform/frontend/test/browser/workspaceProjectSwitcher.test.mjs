  assert.equal(await page.getByRole('option').count(),1);
  assert.deepEqual(await page.evaluate(()=>window.__scopeFixture.requests),['p1'],'searching projects does not fetch their applications');
  await page.getByRole('option',{name:'Payments platform',exact:true}).click();
  await page.getByRole('button',{name:'Application: Loading applications…'}).waitFor();
  assert.equal((await scope()).apps.p2,'merchant','switch restores target project memory');
  await appTrigger().click();
  await page.getByRole('status').filter({hasText:'Loading applications…'}).waitFor();
  assert.equal(await page.getByRole('option').count(),0,'previous project applications cannot appear while loading');
  await page.keyboard.press('Escape');
  await chooseProject('Commerce platform');
  await page.evaluate(()=>window.__scopeFixture.release('p2'));
  await page.getByRole('button',{name:'Application: Mobile checkout'}).waitFor();
  await appTrigger().click();
  assert.equal(await page.getByRole('option',{name:/Merchant/}).count(),0,'late response cannot overwrite current catalog');
  assert.equal(await page.getByRole('option').count(),2);
  await page.keyboard.press('Escape');
  assert.equal(await appTrigger().evaluate(el=>el===document.activeElement),true,'Escape restores triggering control');

  await page.evaluate(()=>window.__scopeFixture.prime('p2',[...window.__scopeFixture.apps.p1,...window.__scopeFixture.apps.p2]));
  await chooseProject('Payments platform');
  await page.getByRole('button',{name:'Application: Merchant portal'}).waitFor();
  await appTrigger().click();
  assert.equal(await page.getByRole('option').count(),2,'cached catalog excludes foreign project rows');
  assert.equal(await page.getByRole('option',{name:/Mobile checkout/}).count(),0);
  assert.equal(await page.getByRole('textbox',{name:'Search applications'}).count(),0,'small catalogs do not add a search control');
  await page.keyboard.press('Home');
  await page.keyboard.press('Enter');
  await page.getByRole('button',{name:'Application: Payment gateway'}).waitFor();
  assert.equal(await appTrigger().evaluate(el=>el===document.activeElement),true,'selection returns keyboard focus to its trigger');
  assert.equal((await scope()).apps.p1,initial.apps.p1,'application selection preserves other project memory');
  assert.equal((await scope()).apps.p2,'gateway');
  const paired=await page.evaluate(()=>window.__scopeFixture.events.filter(event=>event.projectId==='p2'));
  assert.equal(paired.at(-1).apps.p2,'gateway','project-change listeners observe the already-committed application');

  await page.evaluate(()=>{window.__scopeFixture.fail=true;void window.__scopeFixture.invalidate('p2');});
  await appTrigger().click();
