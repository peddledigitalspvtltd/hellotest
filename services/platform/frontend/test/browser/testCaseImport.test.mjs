import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { readFile, writeFile, unlink } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../../../../../testengine/backend/package.json', import.meta.url));
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = new URL('../../', import.meta.url);
test('Test Case import template downloads, parses, preserves structured metadata and queues an observable batch', {timeout:60000}, async()=>{
  const source=await readFile(new URL('../../../../testing/test/browser/testCaseReviewQueue.test.mjs',import.meta.url),'utf8');
  const fixture=source.match(/const fixture = `([\s\S]*?)`;\n\ntest\(/)[1];
  const extra=`\napi.testCases.bulkImport=async input=>{window.importPayload=structuredClone(input);return {transaction_id:'import-test-receipt',job_id:'import-test-job',queued:true,status:'queued',split_count:1}};\n`;
  const name='case-import-'+randomUUID(),html=new URL(name+'.html',root),tsx=new URL(name+'.tsx',root);let browser;
  try {
    await writeFile(html,`<!doctype html><html><body><div id="root"></div><script type="module" src="/${name}.tsx"></script></body></html>`);
    await writeFile(tsx,fixture+extra);
    browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})});
    const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.goto(`${process.env.VITE_TEST_URL||'http://127.0.0.1:5193'}/${name}.html`);
    await page.getByRole('button',{name:'Open create test case options',exact:true}).click();
    await page.getByText('Bulk Import',{exact:true}).click();
    const dialog=page.getByRole('dialog',{name:'Import test cases from external sources'});
    const downloadEvent=page.waitForEvent('download');await dialog.getByRole('button',{name:'Download Template',exact:true}).click();
    const download=await downloadEvent;assert.equal(download.suggestedFilename(),'hellotest-test-case-import-template.csv');
    const path=await download.path();const csv=await readFile(path,'utf8');
    assert.match(csv,/Shared Step Groups/);assert.match(csv,/Parameter Values/);assert.match(csv,/Authoring Mode/);
    await dialog.locator('input[type=file]').setInputFiles({name:download.suggestedFilename(),mimeType:'text/csv',buffer:Buffer.from(csv)});
    const queue=dialog.getByRole('button',{name:/Queue 1 Test Case/});await queue.waitFor();assert.equal(await queue.isEnabled(),true);
    await page.screenshot({path:'/tmp/qaira-case-import-dialog.png'});
    await page.setViewportSize({width:390,height:844});
    const mobileBounds=await dialog.boundingBox();assert.ok(mobileBounds.x>=0&&mobileBounds.width<=390,'Import dialog remains within the mobile viewport');
    await page.screenshot({path:'/tmp/qaira-case-import-dialog-mobile.png'});
    await page.setViewportSize({width:1440,height:1000});
    await queue.click();await dialog.waitFor({state:'detached'});
    await page.getByText(/Test case import queued.*batch process import-t/).waitFor();
    const payload=await page.evaluate(()=>window.importPayload);assert.equal(payload.batches[0].rows.length,1);
    const row=payload.batches[0].rows[0];assert.equal(row.steps.length,3);assert.equal(row.shared_groups[0].steps.length,1);assert.equal(row.parameter_values.username,'sample-user');
    assert.deepEqual(errors,[]);
  }finally{await browser?.close();await Promise.all([unlink(html).catch(()=>{}),unlink(tsx).catch(()=>{})]);}
});
