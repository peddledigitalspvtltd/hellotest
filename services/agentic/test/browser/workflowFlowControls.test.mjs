import assert from 'node:assert/strict';
import test from 'node:test';
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { mkdir, writeFile, unlink } from 'node:fs/promises';
const require = createRequire(new URL('../../../../testengine/backend/package.json', import.meta.url));
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const operations = require(fileURLToPath(new URL('../../backend/workflows/nodeOperations.js', import.meta.url)));
const root = new URL('../../../platform/frontend/', import.meta.url);
const fixture = `
import React,{useState} from 'react';
import {createRoot} from 'react-dom/client';
import {MemoryRouter} from 'react-router-dom';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import {WorkflowCanvas} from '/services/agentic/frontend/workflows/WorkflowCanvas';
import {WorkflowOperationFields} from '/services/agentic/frontend/workflows/WorkflowOperationFields';
import {WorkflowDataView} from '/services/agentic/frontend/workflows/WorkflowDataView';
import {buildNodeDefaults,layoutWorkflow} from '/services/agentic/frontend/workflows/workflowGraph';
import '/src/styles.css';import '/src/dark-theme.css';import '@xyflow/react/dist/style.css';import '/services/agentic/frontend/workflows/WorkflowStudio.css';
const client=new QueryClient({defaultOptions:{queries:{retry:false}}});
const initial=['loop','aggregator','dataOperation','wait','stop'].map((kind,index)=>({id:kind,type:'agenticStep',position:{x:index*310,y:0},data:buildNodeDefaults(kind,index)}));
Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.copiedFlowJson=text;}}});
function Fixture(){
 const [nodes,setNodes]=useState(initial),[selected,setSelected]=useState('loop'),[readOnly,setReadOnly]=useState(false);
 const node=nodes.find(item=>item.id===selected);
 const patch=data=>setNodes(items=>items.map(item=>item.id===selected?{...item,data:{...item.data,...data}}:item));
 const body={id:'body',type:'agenticStep',data:{kind:'transform',label:'Process this batch'},position:{x:0,y:0}};
 const done={id:'done',type:'agenticStep',data:{kind:'output',label:'Collected results'},position:{x:0,y:0}};
 const edges=node.data.kind==='loop' && node.data.loopAction==='workflow'?[{id:'body-edge',source:node.id,target:'body',sourceHandle:'loop'},{id:'return-edge',source:'body',target:node.id,targetHandle:'continue'},{id:'done-edge',source:node.id,target:'done',sourceHandle:'done'}]:[];
 const visible=node.data.kind==='loop'?[node,body,done]:[node];
 return <main className="agentic-studio" style={{minHeight:'100vh',display:'block'}}><nav aria-label="Fixture node selection">{nodes.map(item=><button key={item.id} onClick={()=>setSelected(item.id)}>{item.id}</button>)}<button onClick={()=>setReadOnly(value=>!value)}>Toggle read only</button></nav><div className="flow-controls-fixture" style={{display:'grid',gridTemplateColumns:'minmax(0,1fr) minmax(320px,420px)',gap:16,height:760}}><div style={{height:600,minWidth:0}}><WorkflowCanvas nodes={layoutWorkflow(visible,edges)} edges={edges} nodesDraggable={false} /></div><aside className="studio-inspector" style={{width:'100%',height:'100%',overflow:'auto'}}><div className="studio-inspector-pane"><fieldset disabled={readOnly}><WorkflowOperationFields data={node.data} projectId="fixture" canRun={false} onChange={patch} /></fieldset></div></aside></div><section aria-label="Recorded JSON text"><WorkflowDataView value={'{"status":"passed","literal":"<script>window.flowInjected=true</script>","items":[1,2]}'} defaultMode="json" /></section><output hidden>{JSON.stringify(node.data)}</output><style>{'@media(max-width:600px){.flow-controls-fixture{grid-template-columns:minmax(0,1fr)!important;height:auto!important}.flow-controls-fixture>.studio-inspector{height:auto!important}}'}</style></main>;
}
createRoot(document.getElementById('root')).render(<QueryClientProvider client={client}><MemoryRouter><Fixture/></MemoryRouter></QueryClientProvider>);
`;

test('flow controls author actual loop, merge and item-operation contracts with stable ports and pretty JSON', { timeout: 90000 }, async () => {
  const name = 'workflow-flow-controls-' + randomUUID(), html = new URL(name + '.html', root), tsx = new URL(name + '.tsx', root);
  const screenshots = '/tmp/hellotest-workflow-flow-controls'; let browser, page;
  try {
    await mkdir(screenshots, { recursive: true });
    await writeFile(html, `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><div id="root"></div><script type="module" src="/${name}.tsx"></script></body></html>`);
    await writeFile(tsx, fixture);
    browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) });
    page = await browser.newPage({ viewport: { width: 1440, height: 1050 } }); page.setDefaultTimeout(12000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${process.env.VITE_TEST_URL || 'http://127.0.0.1:5179'}/${name}.html`);
    const state = async () => JSON.parse(await page.locator('output').textContent());
    const choose = name => page.getByRole('navigation', { name: 'Fixture node selection' }).getByRole('button', { name, exact: true }).click();
    await page.getByLabel('Batch size', { exact: true }).fill('2');
    await page.getByLabel('Maximum items', { exact: true }).fill('12');
    assert.equal((await state()).loopBatchSize, 2); assert.equal((await state()).loopMaxIterations, 12);
    assert.equal(await page.locator('.react-flow__handle[data-handleid="loop"]').count(), 1);
    assert.equal(await page.locator('.react-flow__handle[data-handleid="done"]').count(), 1);
    assert.equal(await page.locator('.react-flow__handle[data-handleid="continue"]').count(), 1);
    assert.equal(await page.getByLabel('Field mapping JSON', { exact: true }).count(), 0);
    await page.screenshot({ path: screenshots + '/loop-desktop.png', fullPage: true });
    await page.getByLabel('Action for each item', { exact: true }).selectOption('transform');
    assert.equal(await page.locator('.react-flow__handle[data-handleid="continue"]').count(), 0);
    await page.getByLabel('Field mapping JSON', { exact: true }).waitFor();
    await choose('aggregator');
    await page.getByLabel('Merge inputs', { exact: true }).selectOption('combineMatching');
    assert.deepEqual(JSON.parse(await page.getByLabel('Matching fields JSON', { exact: true }).inputValue()), [{left:'id',right:'id'}]);
    await page.getByLabel('Include matches', { exact: true }).selectOption('outer');
    await page.getByLabel('When fields have the same name', { exact: true }).selectOption('keepBoth');
    assert.equal((await state()).mergeJoin, 'outer'); assert.equal((await state()).mergeClash, 'keepBoth');
    assert.equal(await page.locator('.react-flow__handle[data-handleid="input-1"]').count(), 1);
    assert.equal(await page.locator('.react-flow__handle[data-handleid="input-2"]').count(), 1);
    await page.getByLabel('Merge inputs', { exact: true }).selectOption('chooseInput');
    await page.getByLabel('Return input', { exact: true }).selectOption('2');
    assert.equal((await state()).mergeChooseInput, '2');
    await choose('dataOperation');
    await page.getByLabel('Data operation', { exact: true }).selectOption('sort');
    await page.getByLabel('Sort field 1', { exact: true }).fill('rank');
    await page.getByLabel('Direction 1', { exact: true }).selectOption('desc');
    await page.getByLabel('Value type 1', { exact: true }).selectOption('number');
    let result = await operations.execute({ run:{input_payload:{}}, node:{data:await state()}, sources:[{node_id:'previous',output:{data:[{rank:1},{rank:3},{rank:2}]}}] });
    assert.deepEqual(result.data.map(item=>item.rank), [3,2,1], 'The saved UI sort executes the native item contract');
    await page.getByLabel('Data operation', { exact: true }).selectOption('filter');
    await page.getByLabel('Value path', { exact: true }).fill('item.rank');
    await page.getByLabel('Comparison', { exact: true }).selectOption('greater');
    await page.getByLabel('Compare with JSON', { exact: true }).fill('1');
    result = await operations.execute({ run:{input_payload:{}}, node:{data:await state()}, sources:[{node_id:'previous',output:{data:[{rank:1},{rank:3}]}}] });
    assert.deepEqual(result.data, [{rank:3}]);
    await page.getByLabel('Data operation', { exact: true }).selectOption('switch');
    await page.getByLabel('Route label 1', { exact: true }).fill('Ready for review');
    assert.equal(JSON.parse((await state()).dataRoutes)[0].id, 'passed');
    assert.equal(await page.locator('.react-flow__handle[data-handleid="passed"]').count(), 1);
    await page.getByRole('button', { name:'Add route', exact:true }).click();
    assert.equal(JSON.parse((await state()).dataRoutes)[1].id, 'route_2');
    assert.equal(await page.locator('.react-flow__handle[data-handleid="route_2"]').count(), 1);
    await page.getByLabel('When no route matches', { exact: true }).selectOption('none');
    assert.equal(await page.locator('.react-flow__handle[data-handleid="fallback"]').count(), 0);
    await page.screenshot({ path: screenshots + '/switch-desktop.png', fullPage: true });
    await page.setViewportSize({ width:390, height:900 });
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1), true);
    await page.getByLabel('Data operation', { exact:true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: screenshots + '/switch-mobile.png', fullPage:true });
    await page.getByRole('button', { name:'Toggle read only',exact:true }).click();
    assert.equal(await page.getByLabel('Data operation', { exact:true }).isDisabled(), true);
    assert.equal(await page.getByRole('button', { name:'Add route',exact:true }).isDisabled(), true);
    await page.getByRole('button', { name:'Toggle read only',exact:true }).click();
    await choose('wait'); await page.getByLabel('Wait duration (ms)', { exact:true }).fill('60000');
    assert.equal((await state()).waitMs, 60000); assert.equal((await state()).timeoutMs, '61000');
    await choose('stop'); await page.getByLabel('Error message', { exact:true }).fill('No approved items.');
    assert.equal((await state()).stopMessage, 'No approved items.');
    const recorded=page.getByRole('region', { name:'Recorded JSON text',exact:true });
    await recorded.getByRole('button', { name:'Parsed JSON text',exact:true }).click();
    const parsed=await recorded.getByRole('textbox', { name:'Parsed Data JSON',exact:true }).inputValue();
    assert.match(parsed,/\n/); assert.equal(JSON.parse(parsed).status,'passed');
    await recorded.getByRole('button', { name:'Copy data as JSON',exact:true }).click();
    assert.equal(typeof JSON.parse(await page.evaluate(()=>window.copiedFlowJson)), 'string', 'Copy retains the recorded JSON string type');
    assert.equal(await page.evaluate(()=>Boolean(window.flowInjected)),false);
    assert.deepEqual(errors, []);
  } catch (error) {
    if (page) await page.screenshot({ path:screenshots+'/failure.png',fullPage:true }).catch(()=>{});
    throw error;
  } finally { await browser?.close(); await Promise.allSettled([unlink(html),unlink(tsx)]); }
});
