import assert from 'node:assert/strict';
import test from 'node:test';
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';
import { mkdir, readFile, writeFile, unlink } from 'node:fs/promises';
const require = createRequire(new URL('../../../../testengine/backend/package.json', import.meta.url));
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = new URL('../../../platform/frontend/', import.meta.url);
const base = (await readFile(new URL('agentWorkspace.test.mjs', import.meta.url), 'utf8')).match(/const fixture = `([\s\S]*?)`;\nconst specialists/)[1];

test('workflow edits are recoverable, invalid JSON cannot execute, and narrow screens keep the inspector usable', { timeout: 90000 }, async () => {
  const name = 'studio-usability-' + randomUUID();
  const html = new URL(name + '.html', root), tsx = new URL(name + '.tsx', root);
  const output = '/tmp/qaira-agent-studio-modern';
  let browser;
  try {
    await mkdir(output, { recursive: true });
    await writeFile(html, `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><div id="root"></div><script type="module" src="/${name}.tsx"></script></body></html>`);
    await writeFile(tsx, base.replace("createRoot(document.getElementById('root'))", "api.agenticWorkflows.getRun = async () => structuredClone(window.previewRecord); window.refreshHistory = () => client.invalidateQueries();\ncreateRoot(document.getElementById('root'))"));
    browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.setDefaultTimeout(12000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${process.env.VITE_TEST_URL || 'http://127.0.0.1:5179'}/${name}.html`);
    await page.getByRole('button', { name: 'Open Object Repository Generator', exact: true }).waitFor();
    await page.screenshot({ path: output + '/01-agent-library-desktop.png', fullPage: true });
    const card = page.locator('.agent-library-card').filter({ hasText: 'Test Design Agent' });
    assert.equal(await card.locator('details').getAttribute('open'), null);
    await card.getByText('Inputs & output', { exact: true }).click();
    await card.getByText('Uses', { exact: true }).waitFor();
    await page.evaluate(() => window.navigateWorkspace('/agentic-workflows?view=workflows'));
    assert.equal(await page.getByRole('button', {name:'Executions', exact:true}).count(), 0);
    assert.equal(await page.getByRole('button', {name:'Clear all', exact:true}).count(), 1);
    await page.getByRole('button', { name: 'Start from scratch', exact: true }).click();
    await page.getByRole('button', { name: 'Add manual trigger', exact: true }).click();
    assert.equal(await page.locator('.studio-node').count(), 1);
    await page.getByRole('button', { name: 'Undo graph edit', exact: true }).click();
    await page.getByRole('button', { name: 'Add manual trigger', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Redo graph edit', exact: true }).click();
    await page.locator('.studio-node').waitFor();
    assert.equal(await page.locator('.studio-node').count(), 1);
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await page.getByLabel('Node processing', { exact: true }).selectOption('parallel');
    await page.getByLabel('Maximum concurrent nodes', { exact: true }).fill('8');
    await page.getByLabel('Workflow deadline (ms, optional)', { exact: true }).fill('600000');
    await page.getByRole('button', { name: 'Editor', exact: true }).click();
    await page.getByRole('button', { name: /Add node after Manual trigger/ }).click();
    await page.getByRole('textbox', { name: 'Search nodes', exact: true }).fill('Map JSON');
    await page.locator('.studio-library-list').getByRole('button', { name: /Map JSON/ }).click();
    await page.getByRole('textbox', { name: 'Node name', exact: true }).fill('Shape checkout evidence');
    await page.getByRole('textbox', { name: 'Node name', exact: true }).blur();
    await page.waitForTimeout(400);
    await page.getByRole('button', { name: 'Undo graph edit', exact: true }).click();
    assert.notEqual(await page.getByRole('textbox', { name: 'Node name', exact: true }).inputValue(), 'Shape checkout evidence');
    await page.getByRole('button', { name: 'Redo graph edit', exact: true }).click();
    assert.equal(await page.getByRole('textbox', { name: 'Node name', exact: true }).inputValue(), 'Shape checkout evidence');
    await page.getByRole('button', { name: 'Workflow input', exact: true }).click();
    const input = page.getByRole('textbox', { name: 'Workflow input JSON', exact: true });
    await input.fill('[]');
    await page.getByRole('button', { name: 'Execute workflow', exact: true }).click();
    assert.ok(await page.getByRole('alert').filter({ hasText: 'Workflow input must be a JSON object' }).count());
    assert.equal((await page.evaluate(() => window.workspaceCalls.writes)).length, 0);
    await input.fill('{"request":"Review checkout","release":"r24"}');
    await page.getByRole('button', { name: 'Format JSON', exact: true }).click();
    assert.match(await input.inputValue(), /\n/);
    await page.getByRole('button', { name: 'Close workflow input', exact: true }).click();
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    assert.equal(await page.getByLabel('Node processing', { exact: true }).inputValue(), 'parallel');
    assert.equal(await page.getByLabel('Maximum concurrent nodes', { exact: true }).inputValue(), '8');
    assert.equal(await page.getByLabel('Workflow deadline (ms, optional)', { exact: true }).inputValue(), '600000');
    await page.getByRole('button', { name: 'Editor', exact: true }).click();
    await page.screenshot({ path: output + '/02-studio-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 1000, height: 900 });
    await page.getByRole('button', { name: 'Add node', exact: true }).click();
    assert.equal(await page.getByRole('textbox', { name: 'Node name', exact: true }).isVisible(), true);
    await page.getByRole('button', { name: 'Close node library', exact: true }).click();
    await page.setViewportSize({ width: 390, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
    await page.getByRole('textbox', { name: 'Node name', exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: output + '/03-studio-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.evaluate(() => {
      window.enablePreviewFixture();
      window.previewWorkflow = {id:'history-workflow',project_id:'project',app_type_id:'app',name:'History workflow',description:'',nodes:[],edges:[],status:'draft',variables:{},run_policy:{}};
      window.previewRecord = {id:'history-run',workflow_id:'history-workflow',workflow_name:'History workflow',project_id:'project',app_type_id:'app',status:'completed',trigger_kind:'manual',workflow_snapshot:structuredClone(window.previewWorkflow),node_results:[],input_payload:{},output_payload:{},created_at:'2026-09-10T10:00:00Z',started_at:'2026-09-10T10:00:00Z',completed_at:'2026-09-10T10:00:01Z'};
    });
    await page.evaluate(() => window.refreshHistory());
    await page.getByRole('button', {name:'Back to workflows',exact:true}).click();
    await page.locator('.agentic-workflow-card').filter({hasText:'History workflow'}).click();
    await page.getByRole('button', {name:/Executions/}).click();
    await page.locator('.studio-history-row').filter({hasText:'History workflow'}).click();
    const execution = page.getByRole('dialog', {name:'Workflow execution details',exact:true});
    await execution.waitFor();
    await execution.getByRole('button', {name:'Back',exact:true}).click();
    await execution.waitFor({state:'hidden'});
    assert.equal(await page.locator('.studio-history-row').count(),1, 'Closing execution returns to the same workflow history');
    assert.deepEqual(errors, []);
  } finally { await browser?.close(); await Promise.allSettled([unlink(html), unlink(tsx)]); }
});
