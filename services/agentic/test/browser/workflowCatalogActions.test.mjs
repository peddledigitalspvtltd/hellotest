import assert from 'node:assert/strict';
import test from 'node:test';
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';
import { readFile, writeFile, unlink } from 'node:fs/promises';
const require = createRequire(new URL('../../../../testengine/backend/package.json', import.meta.url));
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = new URL('../../../platform/frontend/', import.meta.url);
const base = (await readFile(new URL('agentWorkspace.test.mjs', import.meta.url), 'utf8')).match(/const fixture = `([\s\S]*?)`;\nconst specialists/)[1];
const setup = `
window.workflowActions={created:[],updated:[],deleted:[],failCreate:false,allowRefundDelete:false};
window.workflowRows=['Checkout','Refund','Unselected'].map((name,index)=>({id:'catalog-'+index,name,project_id:'project',app_type_id:'app',description:name+' review',status:'draft',trigger_kind:'manual',nodes:[],edges:[],settings:{}}));
window.runRows=[{id:'retained-run',workflow_id:'catalog-0',workflow_name:'Checkout',project_id:'project',app_type_id:'app',status:'completed',trigger_kind:'manual',node_results:[],created_at:'2026-10-27T10:00:00Z'}];
api.agenticWorkflows.list=async()=>structuredClone(window.workflowRows);
api.agenticWorkflows.listRuns=async()=>structuredClone(window.runRows);
api.agenticWorkflows.create=async input=>{if(window.workflowActions.failCreate)throw new Error('Workflow creation unavailable');window.workflowActions.created.push(structuredClone(input));const row={...input,id:'created-'+window.workflowActions.created.length};window.workflowRows.push(row);return structuredClone(row);};
api.agenticWorkflows.update=async(id,input)=>{window.workflowActions.updated.push({id,input:structuredClone(input)});const row={...input,id};window.workflowRows=window.workflowRows.map(item=>item.id===id?row:item);return structuredClone(row);};
api.agenticWorkflows.delete=async id=>{window.workflowActions.deleted.push(id);if(id==='catalog-1'&&!window.workflowActions.allowRefundDelete)throw new Error('Workflow manage permission was revoked');window.workflowRows=window.workflowRows.filter(item=>item.id!==id);return {deleted:true};};
`;
const fixture = base.replace('const client = new QueryClient', setup+'\nconst client = new QueryClient');

test('templates create persisted workflows before editing; bulk deletion keeps failures selected and preserves executions', {timeout:90000}, async () => {
  const name='workflow-actions-'+randomUUID(), html=new URL(name+'.html',root), tsx=new URL(name+'.tsx',root);
  let browser;
  try {
    await writeFile(html,`<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><div id="root"></div><script type="module" src="/${name}.tsx"></script></body></html>`);
    await writeFile(tsx,fixture);
    browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})});
    const page=await browser.newPage({viewport:{width:1440,height:1000}});page.setDefaultTimeout(12000);
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    const url=`${process.env.VITE_TEST_URL||'http://127.0.0.1:5197'}/${name}.html?route=${encodeURIComponent('/agentic-workflows?view=workflows')}`;
    await page.goto(url);
    const template=page.getByRole('button',{name:/Data flow Sprint Automator/});
    await template.waitFor();
    await page.evaluate(()=>{window.workflowActions.failCreate=true;});
    await template.click();
    await page.getByText('Workflow creation unavailable',{exact:true}).waitFor();
    assert.equal(await page.getByRole('region',{name:'Workflow editor',exact:true}).count(),0);
    await page.evaluate(()=>{window.workflowActions.failCreate=false;});
    await template.click();
    await page.getByRole('button',{name:'Save changes',exact:true}).waitFor();
    const created=await page.evaluate(()=>window.workflowActions.created);
    assert.equal(created.length,1);
    assert.equal(created[0].settings.library_publication_mode,'automatic');
    assert.equal(created[0].settings.requires_human_review,false);
    assert.equal(created[0].nodes.filter(node=>node.data.kind==='artifactTask').length,4);
    await page.getByRole('button',{name:'Settings',exact:true}).click();
    await page.getByLabel('Workflow name',{exact:true}).fill('My Sprint workflow');
    await page.getByLabel('Node processing',{exact:true}).selectOption('parallel');
    await page.getByRole('button',{name:'Save changes',exact:true}).click();
    await page.getByText('Workflow changes saved.',{exact:true}).waitFor();
    const actions=await page.evaluate(()=>window.workflowActions);
    assert.equal(actions.created.length,1,'Editing must update the created workflow');
    assert.equal(actions.updated.at(-1).id,'created-1');
    assert.equal(actions.updated.at(-1).input.settings.processing_mode,'parallel');
    assert.equal(actions.updated.at(-1).input.settings.max_parallel_nodes,2);
    await page.getByRole('button',{name:'Back to workflows',exact:true}).click();
    await page.getByRole('button',{name:'Tile view',exact:true}).click();
    await page.getByRole('checkbox',{name:'Select Checkout',exact:true}).check();
    await page.getByRole('checkbox',{name:'Select Refund',exact:true}).check();
    await page.getByRole('button',{name:'List view',exact:true}).click();
    await page.getByRole('button',{name:'Delete selected (2)',exact:true}).click();
    const dialog=page.getByRole('dialog',{name:'Delete 2 workflows?',exact:true});
    await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
    assert.deepEqual(await page.evaluate(()=>window.workflowActions.deleted),[]);
    await page.getByRole('button',{name:'Delete selected (2)',exact:true}).click();
    await dialog.getByRole('button',{name:'Delete workflows',exact:true}).click();
    await page.getByText(/1 workflow deleted\. 1 could not be deleted/).waitFor();
    assert.deepEqual(await page.evaluate(()=>window.workflowActions.deleted),['catalog-0','catalog-1']);
    await page.getByRole('button',{name:'Delete selected (1)',exact:true}).waitFor();
    await page.getByRole('button',{name:'Tile view',exact:true}).click();
    assert.equal(await page.getByRole('checkbox',{name:'Select Refund',exact:true}).isChecked(),true);
    assert.equal(await page.getByRole('checkbox',{name:'Select Unselected',exact:true}).isChecked(),false);
    assert.equal(await page.getByRole('checkbox',{name:'Select Checkout',exact:true}).count(),0);
    assert.equal(await page.evaluate(()=>window.runRows.length),1);
    await page.setViewportSize({width:390,height:900});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
    await page.screenshot({path:'/tmp/hellotest-workflow-catalog-mobile.png',fullPage:true});
    await page.setViewportSize({width:1440,height:1000});
    await page.evaluate(()=>window.navigateWorkspace('/agentic-workflows?view=runs'));
    const history=page.getByRole('dialog',{name:'Workflow executions',exact:true});
    await history.waitFor();
    const historyWidth=(await history.boundingBox()).width;
    assert.ok(historyWidth>=1200 && historyWidth<=1440,'Execution history retains its desktop capacity independently of the bounded execution dialog');
    await page.screenshot({path:'/tmp/hellotest-workflow-history-desktop.png',fullPage:true});
    const readonly=await browser.newPage();
    await readonly.goto(url+'&readonly=true');
    await readonly.getByRole('button',{name:'Tile view',exact:true}).click();
    await readonly.getByRole('checkbox',{name:'Select Checkout',exact:true}).check();
    assert.equal(await readonly.getByRole('button',{name:/Delete selected/}).count(),0);
    assert.equal(await readonly.locator('.studio-template-card').count(),0);
    assert.deepEqual(errors,[]);
  } finally {await browser?.close();await Promise.allSettled([unlink(html),unlink(tsx)]);}
});
