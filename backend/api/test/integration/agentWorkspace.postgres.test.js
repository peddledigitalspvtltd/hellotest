// This opt-in test only initializes an EMPTY disposable agent_verify_* database.
// Both SQL adapters must point at that database; no provider model is configured.
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { randomUUID } = require("node:crypto");

test("workspace specialists persist grounded reviews and honest workflow previews", { skip: !process.env.AGENT_WORKSPACE_POSTGRES, timeout: 120_000 }, async () => {
  const primaryUrl = new URL(process.env.DATABASE_URL);
  const observationUrl = new URL(process.env.OBS_DATABASE_URL);
  assert.match(primaryUrl.pathname.slice(1), /^agent_verify_[a-z0-9_]+$/);
  assert.equal(observationUrl.origin + observationUrl.pathname, primaryUrl.origin + primaryUrl.pathname, "Both adapters must use the same disposable database");
  assert.equal(process.env.KNOWLEDGE_VECTOR_STORE, "postgresql", "Keep retrieval inside the disposable database");
  const db = require("../../src/db");
  const obsDb = require("../../src/obsDb");
  try {
    const existing = await db.prepare("SELECT to_regclass('public.projects') AS projects").get();
    assert.equal(existing.projects, null, "This integration test requires an empty disposable database");
    const schemaPath = process.env.AGENT_WORKSPACE_SCHEMA_PATH || process.env.REPOSITORY_AGENT_SCHEMA_PATH || path.resolve(__dirname, "../../../db/schema.sql");
    await db.query(fs.readFileSync(schemaPath, "utf8"));
    await require("../../src/db/bootstrap").ensureRuntimeSchema();
    const userId = randomUUID(), projectId = randomUUID(), appTypeId = randomUUID(), roleId = randomUUID();
    await db.prepare("INSERT INTO roles(id,name) VALUES (?,?)").run(roleId, "Disposable review administrator");
    await db.prepare("INSERT INTO users(id,email,password_hash,name,is_workspace_admin,status) VALUES (?,?,?,?,TRUE,'active')").run(userId, "review-validation@example.test", "not-a-login", "Review validation");
    await db.prepare("INSERT INTO projects(id,name,created_by) VALUES (?,?,?)").run(projectId, "Disposable specialist project", userId);
    await db.prepare("INSERT INTO project_members(id,project_id,user_id,role_id) VALUES (?,?,?,?)").run(randomUUID(), projectId, userId, roleId);
    await db.prepare("INSERT INTO app_types(id,project_id,name,type) VALUES (?,?,?,'web')").run(appTypeId, projectId, "Review application");
    const storyId = randomUUID();
    await db.prepare("INSERT INTO requirements(id,project_id,title,description) VALUES (?,?,?,?)").run(storyId, projectId, "Checkout boundary validation", "Check supported payment methods and explicit validation behavior.");
    const user = { id: userId, role: "admin" };
    const assistant = require("../../src/services/agenticAssistant.service");
    const workflowService = require("../../src/services/agenticWorkflow.service");
    const transactionService = require("../../src/services/workspaceTransaction.service");
    const reviews = [];
    for (const agentId of Object.keys(assistant.AGENT_CATALOG)) {
      const review = await assistant.respond({ project_id: projectId, app_type_id: appTypeId, user, agent_id: agentId, mode: "agent", prompt: "Review current quality evidence and identify supported gaps." });
      assert.equal(review.transaction.status, "completed", agentId);
      assert.equal(review.provenance.generation_mode, "deterministic", "An empty integration registry must not claim model analysis");
      assert.equal(review.result.readiness.status, "limited_evidence");
      assert.ok(review.result.readiness.task_evidence_count > 0);
      assert.ok(review.citations.length > 0);
      assert.ok(review.events.some((event) => event.phase === "context"));
      assert.ok(review.events.some((event) => event.phase === "evaluation"));
      const restored = await assistant.getSession(review.transaction.id, user);
      assert.deepEqual(restored.result, review.result);
      assert.deepEqual(restored.citations, review.citations);
      assert.equal(restored.provenance.input_fingerprint, review.provenance.input_fingerprint);
      assert.equal(restored.provenance.generation_mode, "deterministic");
      reviews.push({ agent_id: agentId, state: restored.session_state, citations: restored.citations.length });
    }
    assert.equal((await obsDb.prepare("SELECT COUNT(*)::INTEGER AS count FROM workspace_transactions WHERE project_id = ? AND category = 'ai_agent'").get(projectId)).count, 10);
    assert.equal((await db.prepare("SELECT COUNT(*)::INTEGER AS count FROM requirements WHERE project_id = ?").get(projectId)).count, 1, "Reviews must not apply suggested story changes");
    const nodes = [
      { id: "output", data: { kind: "output", label: "Review outcome" } },
      { id: "review", data: { kind: "agent", label: "Story review", sampleOutput: "A declared example, not a generated result" } },
      { id: "input", data: { kind: "trigger", label: "Review request" } }
    ];
    const edges = [{ id: "first", source: "input", target: "review" }, { id: "second", source: "review", target: "output" }];
    const workflow = await workflowService.createWorkflow({ project_id: projectId, app_type_id: appTypeId, name: "Review graph", nodes, edges }, user.id);
    const preview = await workflowService.createWorkflowRun(workflow.id, { input_payload: { story_id: storyId, request: "Review checkout boundaries" } }, user.id);
    const persistedPreview = await workflowService.getWorkflowRun(preview.id);
    assert.equal(persistedPreview.execution_mode, "preview");
    assert.equal(persistedPreview.output_payload.execution_mode, "preview");
    assert.equal(persistedPreview.workflow_snapshot.runtime_contract.tools_executed, false);
    assert.equal(persistedPreview.workflow_snapshot.runtime_contract.model_called, false);
    assert.deepEqual(persistedPreview.node_results.map((node) => node.node_id), ["input", "review", "output"]);
    assert.ok(persistedPreview.node_results.every((node) => node.status === "previewed" && node.attempts === 0));
    assert.equal(persistedPreview.node_results[1].input.sources[0].output_available, true);
    await assert.rejects(workflowService.updateWorkflow(workflow.id, { edges: [...edges, { id: "cycle", source: "output", target: "input" }] }, user.id), /cycle/);
    assert.deepEqual((await workflowService.getWorkflow(workflow.id)).edges, edges, "A rejected graph must not mutate the saved workflow");
    assert.equal((await workflowService.listWorkflows({ project_id: projectId, user })).length, 1);
    assert.equal((await workflowService.listWorkflowRuns({ project_id: projectId, user })).length, 1);
    const otherProjectId = randomUUID(), otherAppId = randomUUID();
    await db.prepare("INSERT INTO projects(id,name,created_by) VALUES (?,?,?)").run(otherProjectId, "Separate disposable project", userId);
    await db.prepare("INSERT INTO app_types(id,project_id,name,type) VALUES (?,?,?,'web')").run(otherAppId, otherProjectId, "Separate application");
    await assert.rejects(workflowService.createWorkflow({ project_id: projectId, app_type_id: otherAppId, name: "Invalid application scope", nodes, edges }, user.id), { statusCode: 400 });
    await assert.rejects(workflowService.updateWorkflow(workflow.id, { app_type_id: otherAppId }, user.id), { statusCode: 400 });
    assert.equal((await workflowService.getWorkflow(workflow.id)).app_type_id, appTypeId, "Rejected application moves preserve the saved workflow scope");
    assert.equal((await workflowService.listWorkflows({ project_id: projectId, user })).length, 1);
    const memberId = randomUUID();
    await db.prepare("INSERT INTO users(id,email,password_hash,name,status) VALUES (?,?,?,?,'active')").run(memberId, "review-member@example.test", "not-a-login", "Restricted member");
    await db.prepare("INSERT INTO project_members(id,project_id,user_id,role_id) VALUES (?,?,?,?)").run(randomUUID(), projectId, memberId, roleId);
    const restricted = { id: memberId, role: "member" };
    assert.deepEqual(await workflowService.listWorkflows({ user: restricted }), []);
    assert.deepEqual(await workflowService.listWorkflowRuns({ user: restricted }), []);
    const firstReview = (await transactionService.listTransactions({ project_id: projectId, category: "ai_agent", limit: 1 }))[0];
    await assert.rejects(assistant.getSession(firstReview.id, restricted), { statusCode: 403 });
    await assert.rejects(assistant.listSessions({ project_id: projectId }, restricted), { statusCode: 403 });
    await db.prepare("INSERT INTO role_permissions(role_id,permission_id) SELECT ?,id FROM permissions WHERE code = 'agentic_workflow.view'").run(roleId);
    const permissionService = require("../../src/services/permission.service");
    assert.equal(await permissionService.hasPermission(restricted, "agentic_workflow.view", projectId), true);
    assert.equal(await permissionService.hasPermission(restricted, "transaction.view", projectId), false);
    assert.equal(await permissionService.hasPermission(restricted, "agentic_workflow.run", projectId), false);
    await transactionService.createTransaction({ project_id: projectId, app_type_id: appTypeId, category: "ai_agent", related_kind: "unrelated_agent_work", status: "completed", created_by: user.id });
    await transactionService.createTransaction({ project_id: otherProjectId, app_type_id: otherAppId, category: "ai_agent", related_kind: "agentic_assistant_session", status: "completed", created_by: user.id });
    const visibleReviews = await assistant.listSessions({ project_id: projectId, app_type_id: appTypeId }, restricted);
    assert.equal(visibleReviews.length, 10, "Agent viewers can list specialist history without transaction.view and unrelated records are excluded");
    assert.ok(visibleReviews.every(review => review.related_kind === "agentic_assistant_session" && review.project_id === projectId && review.app_type_id === appTypeId));
    assert.equal((await assistant.listSessions({ project_id: projectId, app_type_id: appTypeId, limit: 3 }, restricted)).length, 3);
    assert.equal((await assistant.getSession(firstReview.id, restricted)).session_state, "completed");
    await assert.rejects(assistant.listSessions({ project_id: projectId, app_type_id: otherAppId }, restricted), { statusCode: 400 });
    const pending = await transactionService.createTransaction({ project_id: projectId, app_type_id: appTypeId, category: "ai_agent", related_kind: "agentic_assistant_session", status: "running", created_by: user.id });
    const pendingSession = await assistant.getSession(pending.id, user);
    assert.equal(pendingSession.session_state, "running");
    assert.equal(pendingSession.result, null);
    const executionService = require("../../src/services/agenticWorkflowExecution.service");
    let executionFailure;
    executionService._internals.diagnostics.onFailure = failure => { executionFailure = failure; };
    const executable = await workflowService.updateWorkflow(workflow.id, { nodes: nodes.map(node => node.id === "review" ? { ...node, data: { ...node.data, agentId: "story-architect", prompt: "Review checkout boundaries using the current project evidence.", knowledgeScope: "stories,knowledge" } } : node) }, user.id);
    assert.equal(executionService.readiness(executable).ready, true);
    await assert.rejects(executionService.start(executable, {}, restricted), { statusCode: 403 });
    const executionInput = { request_id: randomUUID(), input_payload: { request: "Review checkout boundaries" } };
    const started = await executionService.start(executable, executionInput, user);
    await executionService._internals.active.get(started.id)?.promise;
    const actual = await workflowService.getWorkflowRun(started.id);
    if (executionFailure) throw executionFailure;
    assert.equal(actual.execution_mode, "review");
    assert.equal(actual.status, "needs_review", "Deterministic evidence summaries preserve their limitation rather than claiming model success");
    assert.deepEqual(actual.node_results.map(node => node.node_id), ["input", "review", "output"]);
    assert.ok(actual.node_results.every(node => node.status === "completed" && node.attempts === 1));
    assert.ok(actual.node_results[1].output.citation_ids.length > 0);
    const savedReview = await assistant.getSession(actual.node_results[1].output.session_id, user);
    assert.equal(savedReview.session_state, "completed");
    assert.equal(savedReview.transaction.project_id, projectId);
    assert.equal(savedReview.transaction.app_type_id, appTypeId);
    assert.equal(actual.node_results[2].output.reviews[0].session_id, savedReview.transaction.id);
    assert.equal((await executionService.start(executable, executionInput, user)).id, started.id, "Idempotent retries reuse the persisted execution");
    assert.equal((await db.prepare("SELECT COUNT(*)::INTEGER AS count FROM requirements WHERE project_id = ?").get(projectId)).count, 1, "Executed reviews never mutate source stories");
    assert.deepEqual((await workflowService.listWorkflowRuns({ project_id: projectId, user })).map(run => run.execution_mode).sort(), ["preview", "review"]);
    await db.prepare("UPDATE agentic_workflow_runs SET status = 'running', workflow_snapshot = jsonb_set(workflow_snapshot, '{runtime_contract,deadline_at}', ?::jsonb) WHERE id = ?").run(JSON.stringify(new Date(Date.now() - 1000).toISOString()), actual.id);
    const recovered = await workflowService.getWorkflowRun(actual.id);
    assert.equal(recovered.status, "interrupted");
    assert.equal(recovered.node_results[1].output.session_id, savedReview.transaction.id);
    console.log(JSON.stringify({ validated_specialists: reviews, persisted_reviews: 10, restored_review_provenance: true, workflow_execution_mode: persistedPreview.execution_mode, topological_preview: true, invalid_graph_preserved: true, project_permissions_enforced: true, application_scope_preserved: true, specialist_history_without_transaction_permission: true }));
  } finally {
    await obsDb.close();
    await db.close();
  }
});
