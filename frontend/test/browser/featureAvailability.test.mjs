import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../../', import.meta.url));
const require = createRequire(new URL('../../../testengine/backend/package.json', import.meta.url));
const { chromium } = require('playwright');
const host = process.env.BROWSER_TEST_BASE_URL || 'http://127.0.0.1:5179';
const screenshotStage = process.env.ACCESS_SCREENSHOT_STAGE || 'after';
const output = `/tmp/qaira-product-access-${screenshotStage}`;
const fixture = `import React from 'react';
import {createRoot} from 'react-dom/client';
import {AdminApp} from '/src/admin/AdminApp';
import {adminApi,sessionStore} from '/src/admin/api';
import '@fontsource/inter/400.css'; import '@fontsource/inter/500.css'; import '@fontsource/inter/600.css'; import '@fontsource/hanken-grotesk/600.css';
import '/src/admin/admin.css';
const workspace='hellotest.automation.workspace', repository='hellotest.automation.object_repository', agent='hellotest.ai.agentic_workflows';
const state={reads:0,failRead:true,failWrite:false,writes:[],flags:{[workspace]:true,[repository]:true,[agent]:true}};
window.__accessFixture=state;
sessionStore.write({token:'isolated-access-fixture',user:{id:'admin-fixture',name:'Quality Administrator',email:'admin@example.test',role:'admin'}});
adminApi.overview=async()=>({status:'operational',schema:{status:'ready',available_tables:1,required_tables:1,missing_tables:[]},metrics:{administrators:2,users:4,active_integrations:2,integrations:2,enabled_features:3,total_features:3},runtime:{api_port:3000,admin_port:8080}});
adminApi.flags=async()=>{state.reads++; if(state.failRead){state.failRead=false;throw new Error('Temporary connection failure');}return {groups:[{key:'automation',label:'Automation',description:'Author and maintain reliable test automation.',features:[{key:workspace,label:'Automation workspace',description:'Create and run test automation.'},{key:repository,label:'Object repository',description:'Manage reusable page objects and source evidence.'}]},{key:'agents',label:'AI agents',description:'Grounded reviews and repository analysis.',features:[{key:agent,label:'Agent workflows',description:'Prepare, run and review specialist workflows.'}]}],flags:{...state.flags},local_flags:{...state.flags},dependencies:{[repository]:[workspace]}};};
adminApi.updateFlags=async patch=>{state.writes.push(patch);if(state.failWrite){state.failWrite=false;throw new Error('Save failed. Your changes are retained.');}state.flags={...state.flags,...patch};return {updated:true,flags:{...state.flags}};};
createRoot(document.getElementById('root')).render(<AdminApp/>);`;
let browser;
try {
  await mkdir(output, { recursive: true });
  await writeFile(path.join(root, 'access-verification.tsx'), fixture);
  await writeFile(path.join(root, 'access-verification.html'), '<!doctype html><html lang="en"><head><meta name="viewport" content="width=device-width, initial-scale=1" /></head><body><div id="root"></div><script type="module" src="/access-verification.tsx"></script></body></html>');
  browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.route('**/api/**', (route) => { errors.push('Unexpected application request: ' + new URL(route.request().url()).pathname); return route.abort(); });
  await page.goto(`${host}/access-verification.html`);
  await page.getByRole('button', { name: 'Feature availability', exact: true }).click();
  await page.getByRole('heading', { name: 'Feature availability is unavailable' }).waitFor();
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await page.locator('.flag-row').first().waitFor();
  assert.equal(await page.locator('.flag-row').count(), 3);
  await page.getByRole('textbox', { name: 'Find a capability' }).fill('unmatched-feature');
  await page.getByRole('heading', { name: 'No matching capabilities' }).waitFor();
  await page.getByRole('button', { name: 'Clear search', exact: true }).click();
  const workspaceButton = page.getByRole('button', { name: /^Automation workspace/ });
  await workspaceButton.click();
  assert.equal(await workspaceButton.getAttribute('aria-pressed'), 'false');
  await page.getByText('Unavailable until Automation workspace is enabled.').waitFor();
  await page.evaluate(() => { window.__accessFixture.failWrite = true; });
  await page.getByRole('button', { name: 'Publish changes', exact: true }).click();
  await page.getByText('Save failed. Your changes are retained.').waitFor();
  assert.equal(await workspaceButton.getAttribute('aria-pressed'), 'false');
  assert.equal(await page.getByRole('button', { name: 'Publish changes', exact: true }).isEnabled(), true);
  // Another administrator changes an unrelated feature before this save.
  await page.evaluate(() => { window.__accessFixture.flags['hellotest.ai.agentic_workflows'] = false; });
  await page.getByRole('button', { name: 'Publish changes', exact: true }).click();
  await page.getByText('All changes published').waitFor();
  const writes = await page.evaluate(() => window.__accessFixture.writes);
  assert.deepEqual(writes.at(-1), { 'hellotest.automation.workspace': false });
  assert.equal(await page.getByRole('button', { name: /^Agent workflows/ }).getAttribute('aria-pressed'), 'false');
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: `${output}/feature-availability-desktop.png`, fullPage: true });
  const repositoryButton = page.getByRole('button', { name: /^Object repository/ });
  await repositoryButton.focus();
  await page.keyboard.press('Space');
  assert.equal(await repositoryButton.getAttribute('aria-pressed'), 'false');
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click();
  assert.equal(await repositoryButton.getAttribute('aria-pressed'), 'true');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 0);
  await page.screenshot({ path: `${output}/feature-availability-mobile.png`, fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Feature page must fit mobile width');
  assert.deepEqual(errors, []);
  console.log('PASS: feature loading/retry, search, dependency state, dirty-only publish, failed-save recovery, concurrent changes, keyboard discard and mobile fit.');
} finally {
  await browser?.close();
  await rm(path.join(root, 'access-verification.tsx'), { force: true });
  await rm(path.join(root, 'access-verification.html'), { force: true });
}
